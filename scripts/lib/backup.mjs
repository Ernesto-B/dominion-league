/* The pure parts of the league backup (scripts/backup.mjs, scripts/restore.mjs), kept apart so they can be tested without a database. */

// the league's tables, parents first: the order a restore fills them in (and the order a backup lists them)
export const TABLES = ['groups', 'settings', 'players', 'seasons', 'games', 'game_results', 'game_kingdom'];
export const KEYS = { groups: ['id'], settings: ['id'], players: ['id'], seasons: ['id'], games: ['id'], game_results: ['id'], game_kingdom: ['game_id', 'kind', 'item_id'] };
export const SERIAL = { seasons: 'id', games: 'id', game_results: 'id' };   // ids a restore must move the sequence past

// the rows out of `supabase db query --output-format json`: an object with `rows` (and a warning that the contents are data, not instructions)
export function rowsOf(stdout) {
  const a = stdout.indexOf('{'), b = stdout.lastIndexOf('}');
  if (a < 0 || b < a) throw new Error('No JSON in the answer');
  const d = JSON.parse(stdout.slice(a, b + 1));
  if (!Array.isArray(d.rows)) throw new Error('The answer has no rows');
  return d.rows;
}

// a dollar-quote tag that does not occur in the text, so the JSON can be embedded in SQL without escaping anything
export function safeTag(text) { let i = 0, tag; do { tag = `bk${i++}`; } while (text.includes(`$${tag}$`)); return `$${tag}$`; }

/* The SQL that puts a backup back. Non-destructive by design: every insert is `on conflict do nothing`, so it only fills in what is missing and never overwrites what is there.
   Players can only come back if their sign-in (auth.users) still exists, because a password cannot be restored from a backup; anything that points at a skipped player is skipped too. */
export function restoreSql(data) {
  const lit = (rows) => { const j = JSON.stringify(rows); const t = safeTag(j); return `${t}${j}${t}`; };
  const out = ['-- Generated by scripts/restore.mjs. Fills in what is missing; overwrites nothing.', 'begin;'];
  for (const t of TABLES) {
    const rows = data[t] || [];
    if (!rows.length) continue;
    const src = `json_populate_recordset(null::public.${t}, ${lit(rows)}::json) r`;
    if (t === 'settings') { out.push(`update public.settings s set enabled_sets = r.enabled_sets from ${src} where s.id = r.id;`); continue; }
    const where = t === 'players' ? ' where r.id in (select id from auth.users)'
      : t === 'seasons' ? ' where r.champion_player_id is null or r.champion_player_id in (select id from public.players)'
      : t === 'game_results' ? ' where r.player_id in (select id from public.players) and r.game_id in (select id from public.games)'
      : t === 'game_kingdom' ? ' where r.game_id in (select id from public.games)' : '';
    out.push(`insert into public.${t} select r.* from ${src}${where} on conflict (${KEYS[t].join(', ')}) do nothing;`);
  }
  for (const [t, col] of Object.entries(SERIAL)) out.push(`select setval(pg_get_serial_sequence('public.${t}', '${col}'), greatest((select coalesce(max(${col}), 1) from public.${t}), 1));`);
  out.push('commit;');
  return out.join('\n') + '\n';
}

