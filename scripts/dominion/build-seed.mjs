#!/usr/bin/env node
/* Generates supabase/dominion/02_seed_data.sql from supabase/dominion/seed_csv/*.csv.
     node scripts/dominion/build-seed.mjs            # write the file
     node scripts/dominion/build-seed.mjs --check    # exit 1 if the committed file is out of date
   Deterministic (no timestamps), so --check is a reliable "did someone edit a CSV without regenerating?" test. */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { TABLES, ROOT, CSV_DIR, readTable } from './lib/tables.mjs';

const OUT = path.join(ROOT, 'supabase', 'dominion', '02_seed_data.sql');
const BATCH = 100;
const q = id => '"' + id + '"';
const lit = (v, isInt) => {
  if (v === '' || v == null) return 'NULL';
  if (isInt) { if (!/^-?\d+$/.test(v)) throw new Error(`not an integer: ${JSON.stringify(v)}`); return v; }
  return "'" + v.replace(/'/g, "''") + "'";
};

function build() {
  const data = TABLES.map(spec => ({ spec, rows: readTable(spec) }));
  const sums = TABLES.map(s => `--   ${createHash('sha256').update(readFileSync(path.join(CSV_DIR, s.csv))).digest('hex')}  ${s.csv}`);
  const out = [];
  out.push(`-- Dominion collection catalog seed — GENERATED by scripts/dominion/build-seed.mjs from supabase/dominion/seed_csv/.
-- Do not edit by hand: change a CSV and regenerate (\`node scripts/dominion/build-seed.mjs\`).
-- Source CSV SHA-256:
${sums.join('\n')}
--
-- Run ONLY AFTER 01_schema_and_rls.sql. Safe to re-run: it replaces the contents of the nine dominion_* tables
-- with this release, in ONE transaction (readers never see a half-loaded catalog, and any failure — including
-- the row-count assertions at the end — rolls everything back). It never touches the Elo/league tables.
begin;

do $$ begin
  if to_regclass('public.dominion_kingdom_cards') is null then
    raise exception 'Run supabase/dominion/01_schema_and_rls.sql before this seed';
  end if;
end $$;

-- children first, so foreign keys never block the delete`);
  for (const { spec } of [...data].reverse()) out.push(`delete from public.${spec.table};`);
  out.push('');
  for (const { spec, rows } of data) {
    const cols = Object.keys(rows[0]);
    out.push(`-- ${spec.table}: ${rows.length} rows`);
    for (let i = 0; i < rows.length; i += BATCH) {
      const chunk = rows.slice(i, i + BATCH).map(r => '(' + cols.map(c => lit(r[c], spec.ints.includes(c))).join(',') + ')');
      out.push(`insert into public.${spec.table} (${cols.map(q).join(', ')}) values\n${chunk.join(',\n')};`);
    }
    out.push('');
  }
  out.push(`-- All-or-nothing check: if any table does not hold exactly what this release contains, abort the transaction.
do $$
declare bad text := '';
begin`);
  for (const { spec, rows } of data) {
    out.push(`  if (select count(*) from public.${spec.table}) <> ${rows.length} then bad := bad || ' ${spec.table}(expected ${rows.length})'; end if;`);
  }
  out.push(`  if bad <> '' then raise exception 'Dominion seed row-count mismatch:%', bad; end if;
end $$;

commit;
`);
  return out.join('\n');
}

const sql = build();
if (process.argv.includes('--check')) {
  const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return null; } })();
  if (current !== sql) { console.error('supabase/dominion/02_seed_data.sql is out of date — run: node scripts/dominion/build-seed.mjs'); process.exit(1); }
  console.log('02_seed_data.sql is up to date with seed_csv/');
} else {
  writeFileSync(OUT, sql);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${(sql.length / 1024).toFixed(0)} KB, ${TABLES.length} tables)`);
}
